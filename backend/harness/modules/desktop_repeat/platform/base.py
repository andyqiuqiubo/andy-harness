"""L0 平台适配层协议（详细设计 §8.3）。

采集/执行逻辑只依赖这些 Protocol；Windows 实现在 platform/win32/，
其余平台 raise NotImplementedError（本期只保留接口边界）。
"""

from __future__ import annotations

from collections.abc import Callable
from typing import Any, Protocol, runtime_checkable

from ..models import Env, Hit, Miss, MonitorInfo, UiaSnapshot, WindowRef

# 原始输入事件（钩子线程直传，尚未归一化）
RawInput = dict[str, Any]


@runtime_checkable
class InputCapture(Protocol):
    """全局输入钩子（仅录制期安装，停录即摘——降低杀软驻留面，R3）。

    start(on_event=None)：不传 sink 时原始事件进实现自带队列，由 drain() 取
    （§3.2 钩子线程纪律：回调只做入队）。
    """

    def start(self, on_event: Callable[[RawInput], None] | None = None) -> None: ...
    def stop(self) -> None: ...
    def available(self) -> bool: ...
    def drain(self, max_items: int = 0) -> list[RawInput]: ...
    def queue_size(self) -> int: ...
    def stats(self) -> dict[str, int]: ...


@runtime_checkable
class UiInspector(Protocol):
    """UIA 惰性查询面（全部带超时，超时返回 None/Miss）。

    元素引用一律是整数 token（COM 指针不跨套间，§3.5）；release() 归还 token。
    """

    def available(self) -> bool: ...
    def warmup(self) -> None: ...
    def element_from_point(self, x: int, y: int, timeout_ms: int) -> UiaSnapshot | None: ...
    def element_token_from_point(self, x: int, y: int,
                                 timeout_ms: int) -> tuple[int | None, UiaSnapshot | None]: ...
    def focused_element(self, timeout_ms: int = 400) -> tuple[int | None, UiaSnapshot | None]: ...
    def element_by_spec(self, spec: Any, scope: Any, timeout_ms: int) -> Hit | Miss: ...
    def release(self, token: int) -> None: ...
    def read_value(self, element: Any, timeout_ms: int = 500) -> str | None: ...
    def set_value(self, element: Any, text: str, timeout_ms: int = 1000) -> bool: ...
    def invoke(self, element: Any, timeout_ms: int = 1000) -> bool: ...
    def toggle(self, element: Any) -> bool: ...
    def select_item(self, element: Any) -> bool: ...
    def legacy_do_default(self, element: Any) -> bool: ...
    def scroll_item_into_view(self, element: Any) -> bool: ...
    def focus_element(self, element: Any) -> bool: ...
    def patterns_of_element(self, token: Any) -> list[str]: ...
    def snapshot_of_token(self, token: Any, timeout_ms: int = 600) -> UiaSnapshot | None: ...
    def shutdown(self) -> None: ...


@runtime_checkable
class ScreenGrabber(Protocol):
    def available(self) -> bool: ...
    def grab(self, rect: tuple[int, int, int, int] | None = None) -> bytes: ...
    def grab_jpeg(self, rect: tuple[int, int, int, int] | None = None, quality: int = 80) -> bytes: ...
    def grab_gray(self, rect: tuple[int, int, int, int] | None = None) -> Any: ...
    def monitors(self) -> list[MonitorInfo]: ...
    def close(self) -> None: ...


@runtime_checkable
class InputInjector(Protocol):
    """注入面：所有坐标为物理像素（虚拟桌面系）。返回实际插入事件数。"""

    def available(self) -> bool: ...
    def move(self, x: int, y: int) -> int: ...
    def click(self, x: int, y: int, button: str = "left", count: int = 1) -> int: ...
    def press(self, button: str, down: bool, x: int | None = None, y: int | None = None) -> int: ...
    def scroll(self, x: int, y: int, dx: int, dy: int) -> int: ...
    def type_unicode(self, text: str) -> int: ...
    def press_key(self, key: str, down: bool = True) -> int: ...
    def hotkey(self, keys: list[str]) -> int: ...


@runtime_checkable
class WindowManager(Protocol):
    def foreground(self) -> WindowRef | None: ...
    def window_at(self, x: int, y: int) -> WindowRef | None: ...
    def enumerate(self, pid: int | None = None) -> list[WindowRef]: ...
    def find_window(self, hints: dict[str, Any]) -> WindowRef | None: ...
    def focus(self, win: WindowRef) -> bool: ...
    def restore(self, win: WindowRef) -> None: ...
    def alive(self, hwnd: int, timeout_ms: int = 5000) -> bool: ...
    def is_enabled(self, hwnd: int) -> bool: ...
    def top_windows_of(self, pid: int) -> list[WindowRef]: ...


@runtime_checkable
class EnvProvider(Protocol):
    def snapshot(self) -> Env: ...
    def graphics_available(self) -> bool: ...
    def is_elevated(self) -> bool: ...
    def desktop_name(self) -> str: ...
    def apply_dpi_awareness(self) -> None: ...


@runtime_checkable
class InputLease(Protocol):
    """输入设备租约：录制与回放共享同一互斥体（INV-P1/§5.6）。"""

    def acquire(self) -> tuple[bool, int]: ...
    def release(self) -> None: ...
    def held(self) -> bool: ...
